-- Shared Game Night chat. Participants can read the room and post only as their linked profile.
create table if not exists public.game_chat_messages (
  id bigint generated by default as identity primary key,
  participant_id uuid references public.participants(id) on delete set null,
  sender_name text not null,
  message text not null check (char_length(btrim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists game_chat_messages_created_at_idx
  on public.game_chat_messages (created_at);

alter table public.game_chat_messages enable row level security;

grant select, insert on public.game_chat_messages to authenticated;
grant usage, select on sequence public.game_chat_messages_id_seq to authenticated;

drop policy if exists "Signed-in participants can read game chat" on public.game_chat_messages;
create policy "Signed-in participants can read game chat"
on public.game_chat_messages
for select
to authenticated
using (auth.uid() is not null and private.current_participant_id() is not null);

drop policy if exists "Participants can post as themselves" on public.game_chat_messages;
create policy "Participants can post as themselves"
on public.game_chat_messages
for insert
to authenticated
with check (
  auth.uid() is not null
  and participant_id = private.current_participant_id()
  and sender_name = (
    select p.name from public.participants p
    where p.id = private.current_participant_id()
  )
);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'game_chat_messages'
  ) then
    alter publication supabase_realtime add table public.game_chat_messages;
  end if;
end
$$;
