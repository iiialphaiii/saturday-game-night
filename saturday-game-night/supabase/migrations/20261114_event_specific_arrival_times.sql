-- Store participant arrival times per Game Night instead of globally.
create table if not exists public.game_event_arrivals (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.game_nights(id) on delete cascade,
  participant_id uuid not null references public.participants(id) on delete cascade,
  arrival_time text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_id, participant_id)
);

create index if not exists game_event_arrivals_event_id_idx
  on public.game_event_arrivals(event_id);

alter table public.game_event_arrivals enable row level security;
grant select, insert, update on public.game_event_arrivals to authenticated;
grant usage, select on sequence public.game_event_arrivals_id_seq to authenticated;

drop policy if exists "Signed-in participants can view event arrival times" on public.game_event_arrivals;
create policy "Signed-in participants can view event arrival times"
  on public.game_event_arrivals for select to authenticated
  using (auth.uid() is not null and private.current_participant_id() is not null);

drop policy if exists "Participants can set their event arrival time" on public.game_event_arrivals;
create policy "Participants can set their event arrival time"
  on public.game_event_arrivals for insert to authenticated
  with check (
    participant_id = private.current_participant_id()
    and exists (
      select 1 from public.game_nights gn
      where gn.id = event_id and not gn.is_archived
    )
  );

drop policy if exists "Participants can update their event arrival time" on public.game_event_arrivals;
create policy "Participants can update their event arrival time"
  on public.game_event_arrivals for update to authenticated
  using (
    participant_id = private.current_participant_id()
    and exists (
      select 1 from public.game_nights gn
      where gn.id = event_id and not gn.is_archived
    )
  )
  with check (
    participant_id = private.current_participant_id()
    and exists (
      select 1 from public.game_nights gn
      where gn.id = event_id and not gn.is_archived
    )
  );

-- Preserve the existing participant arrival times on the original Game Night.
insert into public.game_event_arrivals (event_id, participant_id, arrival_time)
select gn.id, p.id, p.arrival_time
from public.participants p
join public.event_settings es on es.id = 1
join public.game_nights gn on gn.event_date = es.event_date
where p.arrival_time is not null
  and btrim(p.arrival_time) <> ''
  and p.arrival_time not in ('TBD Pending...', 'Not set', 'Time not confirmed')
on conflict (event_id, participant_id) do nothing;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'game_event_arrivals'
  ) then
    alter publication supabase_realtime add table public.game_event_arrivals;
  end if;
end $$;
