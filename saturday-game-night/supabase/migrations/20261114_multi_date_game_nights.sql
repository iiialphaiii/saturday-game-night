-- Multi-date Game Night support.
-- Preserve the current event as the first Game Night and attach existing content to it.

create table if not exists public.game_nights (
  id uuid primary key default gen_random_uuid(),
  event_title text not null default 'Saturday Game Night',
  event_date date not null unique,
  event_time text not null default '7:00 PM',
  location text,
  voting_open boolean not null default true,
  is_archived boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.game_nights (event_title,event_date,event_time,location,voting_open)
select event_title,event_date,event_time,location,voting_open
from public.event_settings where id=1
on conflict (event_date) do nothing;

alter table public.games add column if not exists event_id uuid references public.game_nights(id) on delete cascade;
alter table public.game_chat_messages add column if not exists event_id uuid references public.game_nights(id) on delete cascade;

update public.games g set event_id=(
  select gn.id from public.game_nights gn
  join public.event_settings es on es.id=1 and gn.event_date=es.event_date
) where g.event_id is null;

update public.game_chat_messages c set event_id=(
  select gn.id from public.game_nights gn
  join public.event_settings es on es.id=1 and gn.event_date=es.event_date
) where c.event_id is null;

alter table public.games alter column event_id set not null;
alter table public.game_chat_messages alter column event_id set not null;

create index if not exists games_event_id_idx on public.games(event_id);
create index if not exists game_chat_messages_event_id_created_at_idx on public.game_chat_messages(event_id,created_at desc);

create table if not exists public.game_attendance (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.game_nights(id) on delete cascade,
  participant_id uuid not null references public.participants(id) on delete cascade,
  status text not null check (status in ('going','maybe','not_going')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_id,participant_id)
);
create index if not exists game_attendance_event_id_idx on public.game_attendance(event_id);

alter table public.game_nights enable row level security;
alter table public.game_attendance enable row level security;

grant select,insert,update,delete on public.game_nights to authenticated;
grant select,insert,update,delete on public.game_attendance to authenticated;
grant usage,select on sequence public.game_attendance_id_seq to authenticated;

drop policy if exists "Game Nights are viewable by everyone" on public.game_nights;
create policy "Game Nights are viewable by everyone" on public.game_nights for select using (true);
drop policy if exists "Admins can create Game Nights" on public.game_nights;
create policy "Admins can create Game Nights" on public.game_nights for insert to authenticated with check (((auth.jwt()->'app_metadata')->>'role')='admin');
drop policy if exists "Admins can update Game Nights" on public.game_nights;
create policy "Admins can update Game Nights" on public.game_nights for update to authenticated using (((auth.jwt()->'app_metadata')->>'role')='admin') with check (((auth.jwt()->'app_metadata')->>'role')='admin');

drop policy if exists "Signed-in participants can view attendance" on public.game_attendance;
create policy "Signed-in participants can view attendance" on public.game_attendance for select to authenticated using (auth.uid() is not null and private.current_participant_id() is not null);
drop policy if exists "Participants can RSVP to open Game Nights" on public.game_attendance;
create policy "Participants can RSVP to open Game Nights" on public.game_attendance for insert to authenticated with check (
  participant_id=private.current_participant_id()
  and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived)
);
drop policy if exists "Participants can update their RSVP" on public.game_attendance;
create policy "Participants can update their RSVP" on public.game_attendance for update to authenticated
using (participant_id=private.current_participant_id() and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived))
with check (participant_id=private.current_participant_id() and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived));
drop policy if exists "Participants can remove their RSVP" on public.game_attendance;
create policy "Participants can remove their RSVP" on public.game_attendance for delete to authenticated
using (participant_id=private.current_participant_id() and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived));

drop policy if exists "Participants can suggest games" on public.games;
create policy "Participants can suggest games" on public.games for insert to authenticated with check (
  suggested_by=private.current_participant_id()
  and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived)
);
drop policy if exists "Admins can update games" on public.games;
create policy "Admins can update games" on public.games for update to authenticated
using (((auth.jwt()->'app_metadata')->>'role')='admin' and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived))
with check (((auth.jwt()->'app_metadata')->>'role')='admin' and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived));
drop policy if exists "Admins can delete games" on public.games;
create policy "Admins can delete games" on public.games for delete to authenticated
using (((auth.jwt()->'app_metadata')->>'role')='admin' and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived));

drop policy if exists "Admins and game admins can manage game rounds" on public.game_rounds;
create policy "Admins and game admins can manage game rounds" on public.game_rounds for all to authenticated
using ((select private.has_scoreboard_access()) and exists(select 1 from public.games g join public.game_nights gn on gn.id=g.event_id where g.id=game_id and not gn.is_archived))
with check ((select private.has_scoreboard_access()) and exists(select 1 from public.games g join public.game_nights gn on gn.id=g.event_id where g.id=game_id and not gn.is_archived));

drop policy if exists "Admins and game admins can manage game round placements" on public.game_round_placements;
create policy "Admins and game admins can manage game round placements" on public.game_round_placements for all to authenticated
using ((select private.has_scoreboard_access()) and exists(select 1 from public.game_rounds r join public.games g on g.id=r.game_id join public.game_nights gn on gn.id=g.event_id where r.id=round_id and not gn.is_archived))
with check ((select private.has_scoreboard_access()) and exists(select 1 from public.game_rounds r join public.games g on g.id=r.game_id join public.game_nights gn on gn.id=g.event_id where r.id=round_id and not gn.is_archived));

drop policy if exists "Admins can manage votes" on public.votes;
create policy "Admins can manage votes" on public.votes for all to authenticated
using (((auth.jwt()->'app_metadata')->>'role')='admin' and exists(select 1 from public.games g join public.game_nights gn on gn.id=g.event_id where g.id=game_id and not gn.is_archived))
with check (((auth.jwt()->'app_metadata')->>'role')='admin' and exists(select 1 from public.games g join public.game_nights gn on gn.id=g.event_id where g.id=game_id and not gn.is_archived));
drop policy if exists "Participants can vote as themselves" on public.votes;
create policy "Participants can vote as themselves" on public.votes for insert to authenticated with check (
  participant_id=private.current_participant_id()
  and exists(select 1 from public.games g join public.game_nights gn on gn.id=g.event_id where g.id=game_id and gn.voting_open and not gn.is_archived)
);
drop policy if exists "Participants can remove their own votes" on public.votes;
create policy "Participants can remove their own votes" on public.votes for delete to authenticated
using (participant_id=private.current_participant_id() and exists(select 1 from public.games g join public.game_nights gn on gn.id=g.event_id where g.id=game_id and not gn.is_archived));

drop policy if exists "Participants can post as themselves" on public.game_chat_messages;
create policy "Participants can post as themselves" on public.game_chat_messages for insert to authenticated with check (
  auth.uid() is not null and participant_id=private.current_participant_id()
  and sender_name=(select p.name from public.participants p where p.id=private.current_participant_id())
  and exists(select 1 from public.game_nights gn where gn.id=event_id and not gn.is_archived)
);

do $$
begin
  if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='game_nights') then
    alter publication supabase_realtime add table public.game_nights;
  end if;
  if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='game_attendance') then
    alter publication supabase_realtime add table public.game_attendance;
  end if;
end $$;
