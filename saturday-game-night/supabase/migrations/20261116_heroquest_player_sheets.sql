create table if not exists public.player_sheets (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.participants(id) on delete cascade,
  sheet_name text not null default 'My HeroQuest Character'
    check (char_length(trim(sheet_name)) between 1 and 80),
  sheet_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists player_sheets_owner_updated_idx on public.player_sheets (owner_id, updated_at desc);

create table if not exists public.player_sheet_audit (
  id bigint generated by default as identity primary key,
  sheet_id uuid references public.player_sheets(id) on delete set null,
  owner_id uuid not null references public.participants(id) on delete cascade,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_participant_id uuid references public.participants(id) on delete set null,
  actor_role text not null,
  action text not null check (action in ('created','updated','deleted')),
  summary text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists player_sheet_audit_sheet_created_idx on public.player_sheet_audit (sheet_id, created_at desc);

alter table public.player_sheets enable row level security;
alter table public.player_sheet_audit enable row level security;
grant select, insert, update, delete on public.player_sheets to authenticated;
grant select on public.player_sheet_audit to authenticated;
grant usage, select on sequence public.player_sheet_audit_id_seq to authenticated;

drop policy if exists "Authenticated users can view player sheets" on public.player_sheets;
create policy "Authenticated users can view player sheets" on public.player_sheets for select to authenticated using (true);
drop policy if exists "Players can create their own sheets" on public.player_sheets;
create policy "Players can create their own sheets" on public.player_sheets for insert to authenticated with check (owner_id = (select private.current_participant_id()));
drop policy if exists "Owners and admins can update player sheets" on public.player_sheets;
create policy "Owners and admins can update player sheets" on public.player_sheets for update to authenticated
  using (owner_id = (select private.current_participant_id()) or (select private.has_scoreboard_access()))
  with check (owner_id = (select private.current_participant_id()) or (select private.has_scoreboard_access()));
drop policy if exists "Owners can delete their own player sheets" on public.player_sheets;
create policy "Owners can delete their own player sheets" on public.player_sheets for delete to authenticated using (owner_id = (select private.current_participant_id()));
drop policy if exists "Admins can view player sheet audit" on public.player_sheet_audit;
create policy "Admins can view player sheet audit" on public.player_sheet_audit for select to authenticated using ((select private.has_scoreboard_access()));

create or replace function private.set_player_sheet_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end;
$$;
drop trigger if exists set_player_sheet_updated_at on public.player_sheets;
create trigger set_player_sheet_updated_at before update on public.player_sheets for each row execute function private.set_player_sheet_updated_at();

create or replace function private.audit_player_sheet_admin_changes()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_owner_id uuid; v_actor_id uuid; v_actor_role text; v_sheet_id uuid;
begin
  v_actor_id := auth.uid();
  v_owner_id := case when tg_op = 'DELETE' then old.owner_id else new.owner_id end;
  v_sheet_id := case when tg_op = 'DELETE' then old.id else new.id end;
  select coalesce(u.raw_app_meta_data->>'role','participant') into v_actor_role
    from auth.users u where u.id = private.current_participant_id();
  if private.has_scoreboard_access() and v_owner_id <> private.current_participant_id() then
    insert into public.player_sheet_audit (sheet_id,owner_id,actor_user_id,actor_participant_id,actor_role,action,summary)
    values (v_sheet_id,v_owner_id,v_actor_id,private.current_participant_id(),coalesce(v_actor_role,'admin'),
      case when tg_op = 'DELETE' then 'deleted' else 'updated' end,
      case when tg_op = 'DELETE' then 'Administrator deleted this character sheet' else 'Administrator updated this character sheet' end);
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
revoke all on function private.audit_player_sheet_admin_changes() from public, anon, authenticated;
drop trigger if exists audit_player_sheet_admin_changes on public.player_sheets;
create trigger audit_player_sheet_admin_changes after update or delete on public.player_sheets for each row execute function private.audit_player_sheet_admin_changes();

