create or replace function private.protect_participant_name()
returns trigger language plpgsql security invoker set search_path = ''
as $$
begin
  if new.name is distinct from old.name and coalesce((auth.jwt()->'app_metadata'->>'role'), '') <> 'admin' then
    raise exception 'Participant names can only be changed by an administrator.';
  end if;
  return new;
end;
$$;
drop trigger if exists protect_participant_name on public.participants;
create trigger protect_participant_name before update on public.participants for each row execute function private.protect_participant_name();

create or replace function public.admin_decide_participant_link_request(p_request_id bigint, p_approve boolean)
returns void language plpgsql security definer set search_path = ''
as $$
declare v_request public.participant_link_requests%rowtype;
begin
  if coalesce((auth.jwt()->'app_metadata'->>'role'), '') <> 'admin' then raise exception 'Administrator access required.'; end if;
  select * into v_request from public.participant_link_requests where id = p_request_id and status = 'pending' for update;
  if not found then raise exception 'This request is no longer pending.'; end if;
  if p_approve then
    insert into private.participant_aliases(auth_user_id, participant_id, approved_by)
    values (v_request.requester_id, v_request.target_participant_id, auth.uid())
    on conflict (auth_user_id) do update set participant_id = excluded.participant_id, approved_by = excluded.approved_by, created_at = now();
  end if;
  update public.participant_link_requests set status = case when p_approve then 'approved' else 'rejected' end, decided_at = now(), decided_by = auth.uid() where id = p_request_id;
end;
$$;
revoke all on function public.admin_decide_participant_link_request(bigint, boolean) from public;
revoke execute on function public.admin_decide_participant_link_request(bigint, boolean) from anon;
grant execute on function public.admin_decide_participant_link_request(bigint, boolean) to authenticated;
