-- Game Night: normalized names, admin controls, identity linking, and round history
create schema if not exists private;
alter table public.participants add column if not exists is_active boolean not null default true;
create unique index if not exists participants_normalized_name_uidx on public.participants (lower(regexp_replace(btrim(name), '\s+', ' ', 'g')));

create table if not exists private.participant_aliases (
  auth_user_id uuid primary key references auth.users(id) on delete cascade,
  participant_id uuid not null references public.participants(id) on delete cascade,
  approved_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);
create table if not exists public.participant_link_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  target_participant_id uuid not null references public.participants(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  requested_at timestamptz not null default now(),
  decided_at timestamptz,
  decided_by uuid references auth.users(id)
);
create unique index if not exists participant_link_requests_one_pending_per_user on public.participant_link_requests(requester_id) where status = 'pending';

create table if not exists public.game_rounds (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete cascade,
  round_number integer not null check (round_number > 0),
  notes text,
  played_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique (game_id, round_number)
);
create table if not exists public.game_round_placements (
  id bigint generated by default as identity primary key,
  round_id bigint not null references public.game_rounds(id) on delete cascade,
  participant_id uuid not null references public.participants(id) on delete restrict,
  place integer not null check (place > 0),
  score numeric,
  notes text,
  created_at timestamptz not null default now()
);
create index if not exists game_rounds_game_id_idx on public.game_rounds(game_id, round_number);
create index if not exists game_round_placements_round_id_idx on public.game_round_placements(round_id, place);

create or replace function private.current_participant_id()
returns uuid language sql stable security definer set search_path = ''
as $$
  select coalesce(
    (select a.participant_id from private.participant_aliases a where a.auth_user_id = (select auth.uid())),
    (select auth.uid())
  );
$$;
revoke all on function private.current_participant_id() from public;
grant usage on schema private to authenticated;
grant execute on function private.current_participant_id() to authenticated;

create or replace function public.get_my_participant_id()
returns uuid language sql stable security invoker set search_path = ''
as $$ select private.current_participant_id(); $$;
revoke all on function public.get_my_participant_id() from public;
grant execute on function public.get_my_participant_id() to authenticated;

