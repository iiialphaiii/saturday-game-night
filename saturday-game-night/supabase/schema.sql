-- Saturday Game Night database
-- Run this entire file in Supabase: SQL Editor > New query > Run.

create table if not exists public.event_settings (
  id integer primary key check (id = 1),
  event_title text not null default 'Saturday Game Night',
  event_date date not null default '2026-11-14',
  event_time text not null default '7:00 PM',
  voting_open boolean not null default true
);

insert into public.event_settings (id, event_title, event_date, event_time, voting_open)
values (1, 'Saturday Game Night', '2026-11-14', '7:00 PM', true)
on conflict (id) do nothing;

create table if not exists public.participants (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 40),
  arrival_time text not null default '7:00 PM',
  created_at timestamptz not null default now()
);

alter table public.participants
  add column if not exists arrival_time text not null default '7:00 PM';

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 80),
  description text,
  suggested_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete cascade,
  participant_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (game_id, participant_id)
);

alter table public.event_settings enable row level security;
alter table public.participants enable row level security;
alter table public.games enable row level security;
alter table public.votes enable row level security;

drop policy if exists "Anyone can read event settings" on public.event_settings;
create policy "Anyone can read event settings" on public.event_settings
  for select to anon, authenticated using (true);

drop policy if exists "Anyone can read participants" on public.participants;
create policy "Anyone can read participants" on public.participants
  for select to anon, authenticated using (true);

drop policy if exists "Participants can register themselves" on public.participants;
create policy "Participants can register themselves" on public.participants
  for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Participants can update themselves" on public.participants;
create policy "Participants can update themselves" on public.participants
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Anyone can read games" on public.games;
create policy "Anyone can read games" on public.games
  for select to anon, authenticated using (true);

drop policy if exists "Signed-in participants can suggest games" on public.games;
create policy "Signed-in participants can suggest games" on public.games
  for insert to authenticated with check (auth.uid() = suggested_by);

drop policy if exists "Anyone can read votes" on public.votes;
create policy "Anyone can read votes" on public.votes
  for select to anon, authenticated using (true);

drop policy if exists "Participants can vote as themselves" on public.votes;
create policy "Participants can vote as themselves" on public.votes
  for insert to authenticated with check (auth.uid() = participant_id);

drop policy if exists "Participants can remove their own votes" on public.votes;
create policy "Participants can remove their own votes" on public.votes
  for delete to authenticated using (auth.uid() = participant_id);

